-- Adds V1/V2 run-comparison columns (LAST_RUN_AT, SCAN_VERSION, TOPOLOGYSHIFTSETID,
-- BASELINE_CONFIG_ID, N_HOURS_TOTAL, CONFIG_CREATED_AT) on top of the 2026-09-25 deployed
-- version. All prior columns and the RT_CONSTRAINT_VALUE-filtered stats are unchanged.

CREATE OR REPLACE PROCEDURE AW.FLOW_ANALYSIS.SP_BENCHMARK_VALIDATION_SCANS("P_STUDY_ID" NUMBER(38,0))
RETURNS TABLE ("CONFIG_ID" NUMBER(38,0), "BRANCH_LABEL" VARCHAR, "CTG_LABEL" VARCHAR, "N" NUMBER(38,0), "MEAN_BIAS_HEADROOM" FLOAT, "MAE_HEADROOM" FLOAT, "MAE_OVER_RATING" FLOAT, "RMSE_HEADROOM" FLOAT, "NRMSE" FLOAT, "PEARSON_R_FLOW" FLOAT, "MEAN_BIAS_LIMIT" FLOAT, "MAE_LIMIT" FLOAT, "LAST_RUN_AT" TIMESTAMP_NTZ, "SCAN_VERSION" VARCHAR, "TOPOLOGYSHIFTSETID" NUMBER(38,0), "BASELINE_CONFIG_ID" NUMBER(38,0), "N_HOURS_TOTAL" NUMBER(38,0), "CONFIG_CREATED_AT" TIMESTAMP_NTZ)
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
    res RESULTSET;
BEGIN
    res := (
        WITH ALL_ROWS AS (
            SELECT
                r.CONFIG_ID,
                COUNT(*) AS N_HOURS_TOTAL,
                MAX(r.COMPUTED_AT) AS MAX_COMPUTED_AT,
                MAX(IFF(r.RT_INTERVAL IS NOT NULL, 1, 0)) AS HAS_RT_INTERVAL
            FROM AW.FLOW_ANALYSIS.FAST_SCAN_RESULTS r
            GROUP BY r.CONFIG_ID
        ),
        RUN_LOG AS (
            SELECT
                CONFIG_ID,
                MAX(RUN_AT) AS LAST_RUN_AT
            FROM AW.FLOW_ANALYSIS.FAST_SCAN_RUN_LOG
            WHERE STATUS = ''SUCCESS''
            GROUP BY CONFIG_ID
        )
        SELECT
            r.CONFIG_ID,
            c.BRANCH_LABEL,
            c.CTG_LABEL,
            COUNT(*) AS N,
            ROUND(AVG(r.RT_ACTUAL_HEADROOM - r.HEADROOM_RT), 2) AS AVG_BIAS_HEADROOM,
            ROUND(AVG(ABS(r.RT_ACTUAL_HEADROOM - r.HEADROOM_RT)), 2) AS MAE_HEADROOM,
            ROUND(AVG(ABS(r.RT_ACTUAL_HEADROOM - r.HEADROOM_RT)) / NULLIF(c.DEFAULT_RATE_B, 0), 4) AS MAE_OVER_RATING,
            ROUND(SQRT(AVG(POWER(r.RT_ACTUAL_HEADROOM - r.HEADROOM_RT, 2))), 2) AS RMSE_HEADROOM,
            ROUND(SQRT(AVG(POWER(r.RT_ACTUAL_HEADROOM - r.HEADROOM_RT, 2))) / NULLIF(c.DEFAULT_RATE_B, 0), 4) AS NRMSE,
            ROUND(CORR(r.RT_CONSTRAINT_VALUE, r.INJECTION_FLOW), 4) AS PEARSON_R_FLOW,
            ROUND(AVG(r.RT_CONSTRAINT_LIMIT - r.REALTIME_RATE_B), 2) AS MEAN_BIAS_LIMIT,
            ROUND(AVG(ABS(r.RT_CONSTRAINT_LIMIT - r.REALTIME_RATE_B)), 2) AS MAE_LIMIT,
            COALESCE(rl.LAST_RUN_AT, ar.MAX_COMPUTED_AT) AS LAST_RUN_AT,
            IFF(ar.HAS_RT_INTERVAL = 1, ''V2'', ''V1'') AS SCAN_VERSION,
            c.TOPOLOGYSHIFTSETID,
            c.BASELINE_CONFIG_ID,
            ar.N_HOURS_TOTAL,
            c.CREATED_AT AS CONFIG_CREATED_AT
        FROM AW.FLOW_ANALYSIS.FAST_SCAN_RESULTS r
        JOIN AW.FLOW_ANALYSIS.FAST_SCAN_CONFIG c
            ON c.CONFIG_ID = r.CONFIG_ID
        JOIN ALL_ROWS ar
            ON ar.CONFIG_ID = r.CONFIG_ID
        LEFT JOIN RUN_LOG rl
            ON rl.CONFIG_ID = r.CONFIG_ID
        WHERE c.SOURCE_TYPE = ''VALIDATION''
          AND c.STUDY_ID = :P_STUDY_ID
          AND r.RT_CONSTRAINT_VALUE IS NOT NULL
          AND r.RT_ACTUAL_HEADROOM IS NOT NULL
        GROUP BY r.CONFIG_ID, c.BRANCH_LABEL, c.CTG_LABEL, c.DEFAULT_RATE_B,
            rl.LAST_RUN_AT, ar.MAX_COMPUTED_AT, ar.HAS_RT_INTERVAL,
            c.TOPOLOGYSHIFTSETID, c.BASELINE_CONFIG_ID, ar.N_HOURS_TOTAL, c.CREATED_AT
        ORDER BY c.BRANCH_LABEL, c.CTG_LABEL, TOPOLOGYSHIFTSETID, SCAN_VERSION
    );
    RETURN TABLE(res);
END;
';
