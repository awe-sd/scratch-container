-- Lines present in the DAM network model (ERCOTDAMPSSELNVIEW) on every day of a month but never
-- present as an SE line device (ISOERCOTSEBRANCHDEVICE) in that month = lines ERCOT does not report
-- in the SE branch feed. STATION_ABSENT_FROM_SE names the end that has no SE device of any kind
-- (typically a private-use network). Keyed by unordered station pair + kV (1 kV tolerance).

SET month_start = '2026-06-01';
SET month_end   = '2026-07-01';

WITH dam AS (
    SELECT LEAST(FROMSTATIONNAME, TOSTATIONNAME) AS A, GREATEST(FROMSTATIONNAME, TOSTATIONNAME) AS B,
           FROMSTATIONKV AS KV, COUNT(DISTINCT "DATE") AS DAM_DAYS, ANY_VALUE(BRANCHNAME) AS BRANCHNAME, MAX(INSERVICE) AS INSERVICE
    FROM AW.DBO.ERCOTDAMPSSELNVIEW
    WHERE "DATE" >= $month_start AND "DATE" < $month_end AND HE = 12 AND FROMSTATIONNAME <> TOSTATIONNAME
    GROUP BY 1, 2, 3
),
se AS (
    SELECT DISTINCT LEAST(FROMSTATIONNAME, TOSTATIONNAME) AS A, GREATEST(FROMSTATIONNAME, TOSTATIONNAME) AS B,
           CAST(KVLEVEL AS NUMBER(6,2)) AS KV
    FROM AW.DBO.ISOERCOTSEBRANCHDEVICE
    WHERE BRANCHDEVICETYPE = 'Line' AND DATEACTIVESTART < $month_end AND DATEACTIVEEND >= $month_start
),
se_station AS (
    SELECT DISTINCT FROMSTATIONNAME AS S FROM AW.DBO.ISOERCOTSEBRANCHDEVICE WHERE DATEACTIVEEND >= $month_start
    UNION SELECT DISTINCT TOSTATIONNAME FROM AW.DBO.ISOERCOTSEBRANCHDEVICE WHERE DATEACTIVEEND >= $month_start
)
SELECT d.BRANCHNAME, d.A AS STATION_A, d.B AS STATION_B, d.KV, d.INSERVICE, d.DAM_DAYS,
       CASE WHEN x.S IS NULL AND y.S IS NULL THEN d.A || ', ' || d.B
            WHEN x.S IS NULL THEN d.A WHEN y.S IS NULL THEN d.B END AS STATION_ABSENT_FROM_SE
FROM dam d
LEFT JOIN se s ON s.A = d.A AND s.B = d.B AND ABS(s.KV - d.KV) <= 1
LEFT JOIN se_station x ON x.S = d.A
LEFT JOIN se_station y ON y.S = d.B
WHERE s.A IS NULL
  AND d.DAM_DAYS >= DATEDIFF(DAY, $month_start, $month_end) - 2
ORDER BY STATION_ABSENT_FROM_SE NULLS LAST, d.KV DESC, d.A;
