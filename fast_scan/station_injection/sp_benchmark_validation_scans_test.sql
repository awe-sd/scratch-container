-- Test variant of SP_BENCHMARK_VALIDATION_SCANS with SCAN_VERSION appended via a
-- small per-config CTE joined on CONFIG_ID; no other columns/joins/filters changed.

CREATE OR REPLACE PROCEDURE AW.FLOW_ANALYSIS.SP_BENCHMARK_VALIDATION_SCANS_TEST("P_STUDY_ID" NUMBER(38,0))
RETURNS TABLE ("CONFIG_ID" NUMBER(38,0), "BRANCH_LABEL" VARCHAR, "CTG_LABEL" VARCHAR, "N" NUMBER(38,0), "MEAN_BIAS_HEADROOM" FLOAT, "MAE_HEADROOM" FLOAT, "MAE_OVER_RATING" FLOAT, "RMSE_HEADROOM" FLOAT, "NRMSE" FLOAT, "PEARSON_R_FLOW" FLOAT, "MEAN_BIAS_LIMIT" FLOAT, "MAE_LIMIT" FLOAT, "SCAN_VERSION" VARCHAR)
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
    res RESULTSET;
BEGIN
    res := (
        WITH SCAN_VER AS (
            SELECT
                CONFIG_ID,
                MAX(IFF(RT_INTERVAL IS NOT NULL, 1, 0)) AS HAS_RT_INTERVAL
            FROM AW.FLOW_ANALYSIS.FAST_SCAN_RESULTS
            GROUP BY CONFIG_ID
        )
        SELECT
            r.CONFIG_ID,
            c.BRANCH_LABEL,
            c.CTG_LABEL,
            COUNT(*) AS N,
            ROUND(AVG(r.RT_ACTUAL_HEADROOM - r.HEADROOM_RT), 2) AS AVG_BIAS_HEADROOM,
            ROUND(AVG(ABS(r.RT_ACTUAL_HEADROOM - r.HEADROOM_RT)), 2) AS MAE_HEADROOM,
            ROUND(AVG(ABS(r.RT_ACTUAL_HEADROOM - r.HEADROOM_RT)) / NULLIF(c.DEFAULT_RATE_B, 0), 4) AS MAE_OVER_RATING,
            ROUND(SQRT(AVG(POWER(r.RT_ACTUAL_HEADROOM - r.HEADROOM_RT, 2))), 2) AS RMSE_HEADROOM,
            ROUND(SQRT(AVG(POWER(r.RT_ACTUAL_HEADROOM - r.HEADROOM_RT, 2))) / NULLIF(c.DEFAULT_RATE_B, 0), 4) AS NRMSE,
            ROUND(CORR(r.RT_CONSTRAINT_VALUE, r.INJECTION_FLOW), 4) AS PEARSON_R_FLOW,
            ROUND(AVG(r.RT_CONSTRAINT_LIMIT - r.REALTIME_RATE_B), 2) AS MEAN_BIAS_LIMIT,
            ROUND(AVG(ABS(r.RT_CONSTRAINT_LIMIT - r.REALTIME_RATE_B)), 2) AS MAE_LIMIT,
            IFF(sv.HAS_RT_INTERVAL = 1, ''V2'', ''V1'') AS SCAN_VERSION
        FROM AW.FLOW_ANALYSIS.FAST_SCAN_RESULTS r
        JOIN AW.FLOW_ANALYSIS.FAST_SCAN_CONFIG c
            ON c.CONFIG_ID = r.CONFIG_ID
        JOIN SCAN_VER sv
            ON sv.CONFIG_ID = r.CONFIG_ID
        WHERE c.SOURCE_TYPE = ''VALIDATION''
          AND c.STUDY_ID = :P_STUDY_ID
          AND r.RT_CONSTRAINT_VALUE IS NOT NULL
          AND r.RT_ACTUAL_HEADROOM IS NOT NULL
        GROUP BY r.CONFIG_ID, c.BRANCH_LABEL, c.CTG_LABEL, c.DEFAULT_RATE_B, sv.HAS_RT_INTERVAL
        ORDER BY c.BRANCH_LABEL, c.CTG_LABEL, r.CONFIG_ID
    );
    RETURN TABLE(res);
END;
';
