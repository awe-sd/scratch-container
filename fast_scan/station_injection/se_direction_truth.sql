-- SE from/to direction truth for one CIM file, expressed as CIM terminal ids.
-- For every SE line device active while the file was in force and matched to a CIM segment by name,
-- the SE from-end is the segment end whose station equals ISOERCOTSEBRANCHDEVICE.FROMSTATIONNAME.
-- Same-station devices have no truth from station names; they are listed with TRUTH = 'UNKNOWN' so the
-- near-flag pattern on them can still be reported.
-- Replace 187 with the CIMFILEID under test. Read-only; runs as AI_READ_ONLY.
WITH w AS (
    SELECT EFFECTIVE_FROM, EFFECTIVE_TO FROM AWDEV.ERCOTRT.ERCOTCIMEFFECTIVEDATE WHERE CIMFILEID = 187
),
seg AS (
    SELECT LINENAME, SEGMENTNAME, SEGMENTCLASS, SEGMENTRDFID, SEGMENTTEID, FROMSTATION, TOSTATION,
           FROMTERMINALNAME, TOTERMINALNAME, FROMTERMINALRDFID, TOTERMINALRDFID,
           TRY_TO_NUMBER(FROMNUM) AS FROMBUS, TRY_TO_NUMBER(TONUM) AS TOBUS,
           COUNT(*) OVER (PARTITION BY LINENAME) AS NSEG
    FROM AWDEV.ERCOTRT.ERCOTLINESEGMENT WHERE CIMFILEID = 187
),
dev AS (
    SELECT d.BRANCHDEVICEID, d.BRANCHDEVICENAME, d.KVLEVEL, d.FROMSTATIONNAME, d.TOSTATIONNAME
    FROM AW.DBO.ISOERCOTSEBRANCHDEVICE d, w
    WHERE d.BRANCHDEVICETYPE = 'Line' AND d.DATEACTIVESTART < w.EFFECTIVE_TO AND d.DATEACTIVEEND >= w.EFFECTIVE_FROM
),
matched AS (
    SELECT d.*, s.*, 'LINENAME' AS MATCHRULE
    FROM dev d JOIN seg s
      ON UPPER(s.LINENAME) = UPPER(d.BRANCHDEVICENAME) AND s.NSEG = 1
     AND ((s.FROMSTATION = d.FROMSTATIONNAME AND s.TOSTATION = d.TOSTATIONNAME) OR (s.FROMSTATION = d.TOSTATIONNAME AND s.TOSTATION = d.FROMSTATIONNAME))
    UNION ALL
    SELECT d.*, s.*, 'LINESEGMENT'
    FROM dev d JOIN seg s
      ON UPPER(s.LINENAME || s.SEGMENTNAME) = UPPER(d.BRANCHDEVICENAME) AND s.NSEG > 1
     AND ((s.FROMSTATION = d.FROMSTATIONNAME AND s.TOSTATION = d.TOSTATIONNAME) OR (s.FROMSTATION = d.TOSTATIONNAME AND s.TOSTATION = d.FROMSTATIONNAME))
),
unique_match AS (
    SELECT * FROM matched QUALIFY COUNT(*) OVER (PARTITION BY BRANCHDEVICEID) = 1 AND COUNT(*) OVER (PARTITION BY SEGMENTRDFID) = 1
)
SELECT BRANCHDEVICEID, BRANCHDEVICENAME, KVLEVEL, FROMSTATIONNAME AS SE_FROMSTATION, TOSTATIONNAME AS SE_TOSTATION,
       LINENAME, SEGMENTNAME, SEGMENTCLASS, SEGMENTRDFID, SEGMENTTEID, MATCHRULE,
       CASE WHEN FROMSTATIONNAME = TOSTATIONNAME THEN 'UNKNOWN'
            WHEN FROMSTATION = FROMSTATIONNAME THEN 'SAME_AS_EXPORT' ELSE 'REVERSED_VS_EXPORT' END AS TRUTH,
       IFF(FROMSTATIONNAME = TOSTATIONNAME, NULL, IFF(FROMSTATION = FROMSTATIONNAME, FROMTERMINALRDFID, TOTERMINALRDFID)) AS SE_FROM_TERMINALRDFID,
       IFF(FROMSTATIONNAME = TOSTATIONNAME, NULL, IFF(FROMSTATION = FROMSTATIONNAME, TOTERMINALRDFID, FROMTERMINALRDFID)) AS SE_TO_TERMINALRDFID,
       IFF(FROMSTATIONNAME = TOSTATIONNAME, NULL, IFF(FROMSTATION = FROMSTATIONNAME, FROMTERMINALNAME, TOTERMINALNAME)) AS SE_FROM_TERMINALNAME,
       IFF(FROMSTATIONNAME = TOSTATIONNAME, NULL, IFF(FROMSTATION = FROMSTATIONNAME, TOTERMINALNAME, FROMTERMINALNAME)) AS SE_TO_TERMINALNAME,
       FROMTERMINALRDFID AS EXPORT_FROM_TERMINALRDFID, TOTERMINALRDFID AS EXPORT_TO_TERMINALRDFID,
       FROMSTATION AS EXPORT_FROMSTATION, TOSTATION AS EXPORT_TOSTATION, FROMBUS AS EXPORT_FROMBUS, TOBUS AS EXPORT_TOBUS
FROM unique_match
ORDER BY TRUTH, BRANCHDEVICENAME;
